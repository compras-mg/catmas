const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(require('node:path').join(__dirname, '../site/index.html'), 'utf8');
const extract = name => html.match(new RegExp('  function ' + name + '\\([^]*?\\n  }'))[0];
const ctx = { hasComplement: true, specIn: { value: '' } };
vm.createContext(ctx);
vm.runInContext(extract('esc') + '\n' + extract('complementSnippet') + '\n' + extract('complementHtml'), ctx);
assert.equal(ctx.complementSnippet('EDITAL', ''), '');
assert.equal(ctx.complementSnippet('Outro texto', 'edital'), '');
assert.equal(ctx.complementSnippet('EDITAIS', 'edital'), '');
assert.match(ctx.complementSnippet('Conforme REFERÊNCIA aprovada', 'referencia'), /<mark>REFERÊNCIA<\/mark>/);
assert.match(ctx.complementSnippet('Conforme REFERE\u0302NCIA aprovada', 'referencia'), /<mark>REFERE\u0302NCIA<\/mark>/);
assert.match(ctx.complementSnippet('a '.repeat(4000) + 'EDITAL ' + 'b '.repeat(4000), 'edital'), /<mark>EDITAL<\/mark>/);
assert.ok(ctx.complementSnippet('a '.repeat(4000) + 'EDITAL ' + 'b '.repeat(4000), 'edital').length < 200);
assert.match(ctx.complementSnippet('<script>edital</script>', 'edital'), /&lt;script&gt;/);
assert.match(ctx.complementHtml(''), /Sem complemento/);
assert.ok(!ctx.complementHtml('texto muito longo', 1).includes('texto muito longo'));
assert.ok(!ctx.complementHtml('texto', 1).includes('<details'));
ctx.specIn.value = 'edital';
assert.match(ctx.complementHtml('Conforme EDITAL', 1), /<mark>EDITAL<\/mark>/);
assert.ok(!ctx.complementHtml('Sem correspondencia', 1).includes('complement-snippet'));
ctx.hasComplement = false;
assert.match(ctx.complementHtml(null), /Indisponível nesta carga/);
const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m => m[1]);
scripts.forEach(script => new vm.Script(script));
console.log('OK: trechos curtos, correspondencia, acentos, escape HTML, carga antiga e sintaxe.');
